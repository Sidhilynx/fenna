// Writes site/js/faces.js: the real Crew pixel faces for the public site.
// The sprites, eye rectangles, face designs and colour names come from the
// app's own source; the colour values are read from the app's styles.css.
// Rerun after the faces or their colours change:
//   node scripts/site-faces.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { SPRITES, eyeRects, spriteRects } from "../apps/crew/src/renderer/pixels.ts";
import { AVATARS, AVATAR_COLORS, MOODS } from "../packages/crew/src/schema.ts";

const css = readFileSync(new URL("../apps/crew/src/renderer/styles.css", import.meta.url), "utf8");

function palette(block) {
  const out = {};
  for (const name of AVATAR_COLORS) {
    const body = block.match(new RegExp(`--av-${name}: (#[0-9a-f]{6})`, "i"));
    const shade = block.match(new RegExp(`--av-${name}-shade: (#[0-9a-f]{6})`, "i"));
    if (!body || !shade) throw new Error(`No colours for ${name}`);
    out[name] = [body[1], shade[1]];
  }
  return out;
}

const dark = css.slice(css.indexOf(":root {"), css.indexOf("@media (prefers-color-scheme: light)"));
const lightStart = css.indexOf(':root[data-theme="light"]');
const light = css.slice(lightStart, css.indexOf("}", lightStart));
const ink = css.match(/--av-ink: (#[0-9a-f]{6})/i)[1];

const sprites = {};
for (const name of AVATARS) {
  const sprite = SPRITES[name];
  const moods = {};
  for (const mood of MOODS) moods[mood] = eyeRects(sprite, mood).map((r) => [r.x, r.y, r.w, r.h]);
  sprites[name] = { rects: spriteRects(sprite).map((r) => [r.x, r.y, r.w, r.h, r.tone]), eyes: moods };
}

const data = { ink, colors: { dark: palette(dark), light: palette(light) }, sprites };
writeFileSync(
  new URL("../site/js/faces.js", import.meta.url),
  `// Generated by scripts/site-faces.mjs from the Crew app. Do not edit by hand.\nwindow.FENNA_FACES = ${JSON.stringify(data)};\n`,
);
