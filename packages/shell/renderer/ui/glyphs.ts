// The grid is 20 units with a 2-unit margin; strokes are round-capped and
// scaled by size so an icon reads equally bold at 12px and at 20px. Each
// glyph has up to three layers, drawn in this order:
//   t  a soft tint (currentColor at low opacity) that gives a shape its body,
//   s  the stroke, the glyph's line work,
//   f  solid fills: dots, the AI mark, the play triangle.
// Frames are rounded at 2.5; dots are r 1.1 to 1.5. Keep new glyphs to that.

export interface Glyph {
  readonly s?: string;
  readonly t?: string;
  readonly f?: string;
  /** Stroke weight relative to the set (1 when absent). */
  readonly w?: number;
}

/** A rounded rectangle as a path. */
function rr(x: number, y: number, w: number, h: number, r: number): string {
  return `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 -${r} ${r}h-${w - 2 * r}a${r} ${r} 0 0 1 -${r} -${r}v-${h - 2 * r}a${r} ${r} 0 0 1 ${r} -${r}z`;
}

/** A circle as a path. */
function c(cx: number, cy: number, r: number): string {
  return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 -${2 * r} 0z`;
}

/** Four-point star with soft concave sides: the AI mark. */
function star(cx: number, cy: number, r: number, k = 0.2): string {
  const q = r * k;
  return `M${cx} ${cy - r}Q${cx + q} ${cy - q} ${cx + r} ${cy}Q${cx + q} ${cy + q} ${cx} ${cy + r}Q${cx - q} ${cy + q} ${cx - r} ${cy}Q${cx - q} ${cy - q} ${cx} ${cy - r}z`;
}

/** A frame's top band (for headers): the frame's top corners, cut flat at y2. */
function band(x: number, y: number, w: number, y2: number, r: number): string {
  return `M${x} ${y2}V${y + r}a${r} ${r} 0 0 1 ${r} -${r}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}V${y2}z`;
}

